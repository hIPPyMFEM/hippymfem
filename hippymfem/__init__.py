"""hIPPyMFEM: deterministic and Bayesian inverse problems on MFEM.

The user supplies a pointwise residual density for the forward PDE; every operator
the inverse problem needs (the adjoint, the parameter Jacobian, the second-order blocks
of the Lagrangian) is generated by automatic differentiation at the quadrature points
and assembled in parallel into hypre matrices, on the host or on GPUs.

Quick start::

    import mfem.par as mfem, jax.numpy as jnp
    from mpi4py import MPI
    import hippymfem as hm

    mfem.Hypre.Init()
    mesh = mfem.ParMesh(MPI.COMM_WORLD,
                        mfem.Mesh.MakeCartesian2D(32, 32, mfem.Element.TRIANGLE))
    Vu = hm.FunctionSpace.H1(mesh, 2)
    Vm = hm.FunctionSpace.H1(mesh, 1)

    def pde_varf(u, m, p, x):
        return jnp.exp(m.val) * hm.inner(u.grad, p.grad)

    bc = hm.DirichletBC(Vu, lambda x: x[1], bdr_attributes=[1, 3])
    pde = hm.PDEVariationalProblem([Vu, Vm, Vu], pde_varf, bc,
                                   bc.homogeneous(), is_fwd_linear=True)
"""


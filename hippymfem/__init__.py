#: The UFL-flavoured helpers of :mod:`hippymfem.fem.jaxops` (``inner``, ``dot``, ``div``,
#: ...).  Listed here so ``hm.inner`` and ``from hippymfem import *`` work, but resolved
#: lazily by ``__getattr__`` below, so that ``import hippymfem`` does not import JAX
#: and bring up a backend when the residual-density route is not used.
_JAX_NAMES = ("inner", "dot", "div", "tr", "sym", "skew", "Identity", "outer", "cross",
              "nabla_grad", "sqrt", "exp", "ln", "log", "norm2")
_KERNEL_NAMES = ("QuadratureKernel", "BoundaryKernel", "GroupKernel", "Field",
                 "set_device")

__all__ = (["__version__", "version_info", "config"]
           + list(_common_all) + list(_alg_all) + list(_fem_all)
           + list(_mod_all) + list(_uq_all) + list(_mcmc_all)
           + list(_JAX_NAMES))


def __getattr__(name):
    """Expose the JAX-dependent layers lazily (PEP 562).

    Uses ``importlib.import_module`` rather than ``from .fem import jaxops``, which
    asks the parent package for the attribute first, re-enters this function (and
    ``fem``'s) and recurses without end.
    """
    if name in _KERNEL_NAMES:
        import importlib

        return getattr(importlib.import_module("hippymfem.fem.kernel"), name)
    if name in _JAX_NAMES:
        import importlib

        return getattr(importlib.import_module("hippymfem.fem.jaxops"), name)
    raise AttributeError("module %r has no attribute %r" % (__name__, name))

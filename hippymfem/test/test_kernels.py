"""AD element kernels against MFEM's own integrators.

Every block the inverse problem needs is generated by differentiating a
pointwise residual density.  This compares those blocks against hand-written
MFEM integrators on the *same* integration rule, where an exact match is the
only acceptable answer.

Run with ``mpirun -n N python -m hippymfem.test.test_kernels``.
"""

import numpy as np
from mpi4py import MPI

import mfem.par as mfem
import jax.numpy as jnp

import hippymfem as hp
from hippymfem.fem.spaces import FunctionSpace
from hippymfem.fem.elementbatch import MeshBatches
from hippymfem.fem.kernel import QuadratureKernel
from hippymfem.fem.assemble import assemble_matrix, assemble_vector
from hippymfem.fem.jaxops import div, inner, sym
from hippymfem.modeling.variables import ADJOINT, PARAMETER, STATE
from hippymfem.common.parvector import ParVector

COMM = MPI.COMM_WORLD
RANK = COMM.rank
NP = COMM.size
FAILS = []


def check(name, ok, detail=""):
    if RANK == 0:
        print("  [%s] %s %s" % ("ok  " if ok else "FAIL", name, detail), flush=True)
    if not ok:
        FAILS.append(name)


def relerr_op(A, B, template):
    """Relative difference of two HypreParMatrix actions on a random vector."""
    x = ParVector(COMM, A.Width())
    y1 = ParVector(COMM, A.Height())
    y2 = ParVector(COMM, A.Height())
    hp.parRandom.set_seed(99)
    hp.parRandom.normal(1.0, x)
    A.Mult(x.hypre, y1.hypre)
    B.Mult(x.hypre, y2.hypre)
    n = y1.norm("l2")
    y2.axpy(-1.0, y1)
    return y2.norm("l2") / max(n, 1e-300)


def make_mesh(kind, n=6):
    if kind == "tri":
        m = mfem.Mesh.MakeCartesian2D(n, n, mfem.Element.TRIANGLE)
    elif kind == "quad":
        m = mfem.Mesh.MakeCartesian2D(n, n, mfem.Element.QUADRILATERAL)
    elif kind == "tet":
        m = mfem.Mesh.MakeCartesian3D(n, n, n, mfem.Element.TETRAHEDRON)
    elif kind == "hex":
        m = mfem.Mesh.MakeCartesian3D(n, n, n, mfem.Element.HEXAHEDRON)
    else:
        raise ValueError(kind)
    return mfem.ParMesh(COMM, m)


def _split_mesh_n():
    """Cells a side of a hexahedral mesh with at least 512 elements on every rank, twice
    the chunk planner's floor, so the planner can split a rank's batch."""
    n = 10
    while n ** 3 < 512 * NP:
        n += 1
    return n


